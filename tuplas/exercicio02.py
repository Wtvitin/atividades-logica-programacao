# Exercício 02 — Acessando elementos
# Objetivo: acessar elementos de uma tupla por índices positivos e negativos.

tupla = ("a", "b", "c", "d", "e")
print(f"Tupla: {tupla}\n")

print(f"Primeiro elemento: {tupla[0]}")
print(f"Último elemento: {tupla[-1]}")
print(f"Índice 2: {tupla[2]}")
print(f"Índice -2: {tupla[-2]}")
